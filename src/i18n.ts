// DYNAMIC CONTENT TRANSLATION LAYER (free Google Translate, no API key)
// ==========================================================================

const TRANSLATE_ENDPOINT = 'https://translate.googleapis.com/translate_a/single';

/**
 * Translates a single string using the free (keyless) Google Translate
 * endpoint. Throws on failure so callers can fall back to the original text.
 */
export async function googleTranslate(text: string, targetLang: SupportedLanguage): Promise<string> {
  if (!text || targetLang === 'en') return text;
  const params = new URLSearchParams({ client: 'gtx', sl: 'auto', tl: targetLang, dt: 't', q: text });
  const res = await fetch(`${TRANSLATE_ENDPOINT}?${params.toString()}`);
  if (!res.ok) throw new Error(`Translation request failed (${res.status})`);
  const data = await res.json();
  const segments = data?.[0];
  if (!Array.isArray(segments)) throw new Error('Unexpected translation response');
  return segments.map((seg: unknown[]) => seg?.[0] || '').join('');
}

/**
 * Translates a short label (title, tag, focus area). Falls back to the
 * original text on any failure so the UI never breaks.
 */
export async function translateShortLabel(label: string, targetLang: SupportedLanguage): Promise<string> {
  if (!label || targetLang === 'en') return label;
  try {
    const result = await googleTranslate(label, targetLang);
    return result || label;
  } catch (e) {
    console.warn('Short-label translation failed, using original:', e);
    return label;
  }
}

/** Non-translatable tokens (code, URLs, emphasis markers) are fenced with these. */
const PLACEHOLDER_RE = /(`[^`]*`|\[[^\]]*\]\([^)]*\)|https?:\/\/\S+|\*\*|~~|\*|__)/g;

function protectInline(text: string): { fenced: string; originals: string[] } {
  const originals: string[] = [];
  let index = 0;
  const fenced = text.replace(PLACEHOLDER_RE, (match) => {
    originals.push(match);
    return `§${index++}§`;
  });
  return { fenced, originals };
}

function restoreInline(fenced: string, originals: string[]): string {
  return fenced.replace(/§(\d+)§/g, (_m, i) => originals[Number(i)] ?? '');
}

async function translateTextLine(text: string, targetLang: SupportedLanguage): Promise<string> {
  const { fenced, originals } = protectInline(text);
  const translated = await googleTranslate(fenced, targetLang);
  return restoreInline(translated, originals);
}

const MAX_CHUNK = 3500;

async function translateChunks(text: string, targetLang: SupportedLanguage): Promise<string> {
  if (text.length <= MAX_CHUNK) return translateTextLine(text, targetLang);
  const parts: string[] = [];
  let start = 0;
  while (start < text.length) {
    let end = Math.min(start + MAX_CHUNK, text.length);
    if (end < text.length) {
      const rel = text.lastIndexOf(' ', end);
      if (rel > start + MAX_CHUNK / 2) end = rel;
    }
    parts.push(await translateTextLine(text.slice(start, end), targetLang));
    start = end;
  }
  return parts.join(' ');
}

/**
 * Translates a markdown document while preserving its structure: headings,
 * blockquotes, lists, tables, code fences, URLs and inline code all stay
 * intact — only human-readable words are translated.
 */
export async function translatePaperContent(content: string, targetLang: SupportedLanguage): Promise<string> {
  if (!content || targetLang === 'en') return content;

  const blocks = content.split(/\n{2,}/);
  const out: string[] = [];

  for (const block of blocks) {
    const lines = block.split('\n');

    // Code fence: leave untouched.
    if (lines[0]?.startsWith('```') || lines[0]?.startsWith('~~~')) {
      out.push(block);
      continue;
    }

    // Table: translate each cell individually, keep the delimiter row as-is.
    if (lines.length > 1 && lines.every(l => l.includes('|'))) {
      const rows: string[] = [];
      for (const line of lines) {
        if (/^\|?[\s:-]+\|[\s:-]*(?:\|[\s:-]*)*\|?$/.test(line) && line.includes('-')) {
          rows.push(line);
          continue;
        }
        const cells = line.split('|');
        const translatedCells: string[] = [];
        for (const cell of cells) {
          translatedCells.push(cell.trim() ? await translateChunks(cell.trim(), targetLang) : cell);
        }
        rows.push(translatedCells.join('|'));
      }
      out.push(rows.join('\n'));
      continue;
    }

    const newLines: string[] = [];
    for (const line of lines) {
      if (!line.trim()) {
        newLines.push(line);
        continue;
      }
      const heading = line.match(/^(\s*#{1,6})\s+(.*)$/);
      if (heading) {
        const text = await translateChunks(heading[2], targetLang);
        newLines.push(`${heading[1]} ${text}`);
        continue;
      }
      const quote = line.match(/^((?:\s*>)+)\s?(.*)$/);
      if (quote && quote[2]) {
        const text = await translateChunks(quote[2], targetLang);
        newLines.push(`${quote[1]} ${text}`);
        continue;
      }
      const list = line.match(/^(\s*(?:[-*+]|\d+\.)\s+)(.*)$/);
      if (list && list[2]) {
        const text = await translateChunks(list[2], targetLang);
        newLines.push(`${list[1]}${text}`);
        continue;
      }
      newLines.push(await translateChunks(line, targetLang));
    }

    out.push(newLines.join('\n'));
  }

  return out.join('\n\n');
}





